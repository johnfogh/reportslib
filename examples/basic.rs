//! Write a sample self-contained report to `report.html` in the current directory.
use reportslib::Report;

fn main() -> std::io::Result<()> {
    // 1x1 red PNG
    let png = [
        0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44,
        0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x02, 0x00, 0x00, 0x00, 0x90,
        0x77, 0x53, 0xde, 0x00, 0x00, 0x00, 0x0c, 0x49, 0x44, 0x41, 0x54, 0x08, 0xd7, 0x63, 0xf8,
        0xcf, 0xc0, 0x00, 0x00, 0x00, 0x03, 0x00, 0x01, 0x00, 0x05, 0xfe, 0xd4, 0xef, 0x00, 0x00,
        0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
    ];

    Report::new("Session summary")
        .meta("Generated", "2026-10-18")
        .meta("Course", "demo")
        .heading(2, "Overview")
        .paragraph("Hits recorded during the session. This file is self-contained.")
        .table(
            ["Device", "Hits"],
            [["sensor-01", "12"], ["sensor-02", "7"]],
        )
        .heading(2, "Overlay")
        .image_png(png, "sample overlay")
        .list(false, ["No external CSS", "No external JS", "Images as data URIs"])
        .script("document.documentElement.dataset.ready = '1';")
        .write_to("report.html")?;

    println!("wrote report.html");
    Ok(())
}
